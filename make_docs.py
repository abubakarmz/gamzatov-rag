def pct(part, whole):
    return round(100 * int(part) / int(whole)) if int(whole) else 0


def rag_errors(model):
    """Ошибки с библиотекой: в скольких из них поиск всё-таки нашёл карточку с ответом."""
    from rag import Library
    from step4_experiments import normalize
    library = Library()
    by_id = {str(q["id"]): q for q in questions}
    wrong = [r for r in answers if r["model"] == model and r["mode"] == "rag" and r["result"] == "wrong"
             and not by_id[r["id"]].get("trap")]
    found = 0
    for r in wrong:
        cards = library.search(r["question"])
        text = normalize(" ".join(f"{c['source']} {c['section']} {c['text']}" for c in cards))
        found += any(k in text for k in by_id[r["id"]]["keywords"])
    return found, len(wrong)


def styles(font, size):
    base = ParagraphStyle("base", fontName=font, fontSize=size, leading=size * 1.45,
                          alignment=TA_JUSTIFY, firstLineIndent=1.0 * cm if font == "TNR" else 0,
                          spaceAfter=4)
    return {
        "p": base,
        "plain": ParagraphStyle("plain", parent=base, firstLineIndent=0),
        "center": ParagraphStyle("center", parent=base, alignment=TA_CENTER, firstLineIndent=0),
        "h1": ParagraphStyle("h1", parent=base, fontName=font + "-B", fontSize=size + 4,
                             leading=(size + 4) * 1.3, alignment=TA_CENTER, firstLineIndent=0,
                             spaceBefore=6, spaceAfter=10),
        "h2": ParagraphStyle("h2", parent=base, fontName=font + "-B", fontSize=size + 1,
                             leading=(size + 1) * 1.35, firstLineIndent=0, spaceBefore=10, spaceAfter=6,
                             alignment=0),
        "small": ParagraphStyle("small", parent=base, fontSize=size - 2, leading=(size - 2) * 1.35,
                                firstLineIndent=0, alignment=0),
        "cap": ParagraphStyle("cap", parent=base, fontSize=size - 1, alignment=TA_CENTER,
                              firstLineIndent=0, textColor=HexColor("#52514e")),
        "box": ParagraphStyle("box", parent=base, firstLineIndent=0, alignment=0,
                              backColor=HexColor("#eef4fc"), borderPadding=8, spaceBefore=8,
                              spaceAfter=12, borderColor=HexColor("#86b6ef"), borderWidth=0.6),
    }


def table(rows, widths, st, header=True):
    data = [[Paragraph(str(c), st["small"]) for c in row] for row in rows]
    t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
    style = [("GRID", (0, 0), (-1, -1), 0.4, HexColor("#b9b8b3")),
             ("VALIGN", (0, 0), (-1, -1), "TOP"),
             ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
    if header:
        style.append(("BACKGROUND", (0, 0), (-1, 0), HexColor("#eef4fc")))
    t.setStyle(TableStyle(style))
    return t


def chart(name, width_cm, st, caption):
    path = CHARTS_DIR / name
    if not path.exists():
        return []
    img = Image(str(path))
    ratio = img.imageHeight / img.imageWidth
    img.drawWidth, img.drawHeight = width_cm * cm, width_cm * cm * ratio
    return [KeepTogether([img, Paragraph(caption, st["cap"])])]


def page_number(canvas, doc):
    if doc.page > 1:
        canvas.setFont("TNR", 10)
        canvas.drawCentredString(A4[0] / 2, 1.2 * cm, str(doc.page))


def build(path, story, margins=(3, 1.5, 2, 2)):
    left, right, top, bottom = margins
    DOCS.mkdir(exist_ok=True)
    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=left * cm, rightMargin=right * cm,
                      topMargin=top * cm, bottomMargin=bottom * cm,
                      title=path.stem.replace("_", " ")).build(
        story, onFirstPage=page_number, onLaterPages=page_number)


